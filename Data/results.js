const addHoverHandlers = (fixedPart, scrollPart) => {
    const fixedRows = fixedPart.querySelectorAll('.detailed-data-row');
    const scrollRows = scrollPart.querySelectorAll('.detailed-data-row');
    const headerCells = scrollPart.querySelectorAll('.detailed-header-row .gp-col');
    const allCells = scrollPart.querySelectorAll('.detailed-data-row .detailed-cell');

    const clearAllHighlights = () => {
        fixedRows.forEach(row => row.classList.remove('hovered-row'));
        scrollRows.forEach(row => row.classList.remove('hovered-row'));
        scrollPart.querySelectorAll('.detailed-cell').forEach(cell => {
            cell.classList.remove('highlighted-cell', 'column-highlighted');
        });
        headerCells.forEach(cell => {
            cell.classList.remove('column-header-highlighted', 'column-highlighted');
        });
    };

    const highlightColumn = colIndex => {
        headerCells.forEach((cell, index) => {
            if (index === colIndex) cell.classList.add('column-header-highlighted');
        });
        scrollRows.forEach(row => {
            const cell = row.querySelector(`.gp-col[data-col="${colIndex}"]`);
            if (cell) cell.classList.add('column-highlighted');
        });
    };

    headerCells.forEach((headerCell, colIndex) => {
        headerCell.addEventListener('mouseenter', () => {
            clearAllHighlights();
            highlightColumn(colIndex);
        });
        headerCell.addEventListener('mouseleave', clearAllHighlights);
    });

    fixedRows.forEach((fixedRow, index) => {
        fixedRow.addEventListener('mouseenter', () => {
            clearAllHighlights();
            fixedRow.classList.add('hovered-row');
            if (scrollRows[index]) scrollRows[index].classList.add('hovered-row');
        });
        fixedRow.addEventListener('mouseleave', clearAllHighlights);
    });

    allCells.forEach(cell => {
        cell.addEventListener('mouseenter', e => {
            e.stopPropagation();
            clearAllHighlights();

            const row = cell.closest('.detailed-data-row');
            const rowIndex = row?.dataset.rowIndex;
            const colIndex = cell.dataset.col;

            if (row) {
                row.classList.add('hovered-row');
                if (fixedRows[rowIndex]) fixedRows[rowIndex].classList.add('hovered-row');
            }

            if (colIndex !== undefined && colIndex !== 'sum') {
                highlightColumn(parseInt(colIndex));
            }

            cell.classList.add('highlighted-cell');
        });
        cell.addEventListener('mouseleave', e => {
            e.stopPropagation();
            clearAllHighlights();
        });
    });

    scrollRows.forEach((scrollRow, index) => {
        scrollRow.addEventListener('mouseenter', e => {
            if (e.target !== scrollRow) return;
            clearAllHighlights();
            scrollRow.classList.add('hovered-row');
            if (fixedRows[index]) fixedRows[index].classList.add('hovered-row');
        });
        scrollRow.addEventListener('mouseleave', e => {
            if (e.target === scrollRow && !scrollRow.contains(e.relatedTarget)) {
                clearAllHighlights();
            }
        });
    });
};

