const calculateRaceWinners = () => {
    const winners = {};
    const allGPs = getAllGPs();

    allGPs.forEach(gpId => {
        const results = detailedResults[gpId];
        if (!results) return;
        if (!hasRealResults(gpId, false)) return;

        for (const [driverId, value] of Object.entries(results)) {
            if (driverId === '000') continue;
            if (value === 25) {
                if (!winners[driverId]) winners[driverId] = { driverId, wins: 0 };
                winners[driverId].wins += 1;
                break;
            }
        }
    });

    return Object.values(winners)
        .sort((a, b) => b.wins - a.wins)
        .map(entry => ({ driver: findDriverById(entry.driverId), wins: entry.wins }))
        .filter(entry => entry.driver);
};

